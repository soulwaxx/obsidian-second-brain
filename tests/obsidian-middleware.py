    def swap_before_quarantine(src, dst, *args, **kwargs):
        if src == "index.md":
            index.unlink()
            user_file.rename(index)
        return real_rename(src, dst, *args, **kwargs)

    with patch.object(sync_module.os, "rename", swap_before_quarantine):
        sync_module.sync_directory(wiki, "nested")
    assert index.read_text() == "preserve me\n"

