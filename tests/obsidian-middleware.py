    real_open = builtins.open

    def swap_for_symlink(file, mode="r", *args, **kwargs):
        if Path(file) == index and mode == "w":
            index.unlink()
            index.symlink_to(outside)
        return real_open(file, mode, *args, **kwargs)

    with patch("builtins.open", swap_for_symlink):
        sync_module.sync_directory(wiki, "nested")
